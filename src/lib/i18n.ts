const patterns: [RegExp, (m: RegExpExecArray) => string][] = [
  [/^Invoice (.+)$/, (m) => `فاتورة ${m[1]}`],
  [/^Credit note (.+)$/, (m) => `إشعار دائن ${m[1]}`],
  [/^Bill of lading (.+)$/, (m) => `بوليصة شحن ${m[1]}`],
  [/^Void (.+)\?$/, (m) => `إلغاء الفاتورة ${m[1]}؟`],
  [/^Delete (.+)\?$/, (m) => `حذف ${m[1]}؟`],
  [/^Remove the leg (.+)\?$/, (m) => `إزالة المرحلة ${m[1]}؟`],
  [/^Remove (.+)\?$/, (m) => `إزالة ${m[1]}؟`],
  [/^Remove (.+)$/, (m) => `إزالة ${m[1]}`],
  [/^Vehicles \((\d+)\)$/, (m) => `المركبات (${m[1]})`],
  [/^Sort by (.+)$/, (m) => `ترتيب حسب ${t(m[1])}`],
];

/** Translate an interface string; unknown strings (names, data) pass through. */
export function t(text: string): string {
  if (current !== "ar" || typeof text !== "string") return text;
  const hit = ar[text];
  if (hit) return hit;
  for (const [re, fn] of patterns) {
    const m = re.exec(text);
    if (m) return fn(m);
  }
  return text;
}
