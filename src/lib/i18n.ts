// Interface language: English or Arabic (right to left). The choice is kept
// in the "lang" cookie; the root route reads it for each request and calls
// setLang before the page renders, so server and browser agree.

export type Lang = "en" | "ar";
export const LANG_COOKIE = "lang";

let current: Lang = "en";

export function setLang(lang: Lang) {
  current = lang;
}
export function getLang(): Lang {
  return current;
}
export function isLang(value: unknown): value is Lang {
  return value === "en" || value === "ar";
}
export function langFromCookie(cookie: string | null | undefined): Lang {
  const match = /(?:^|;\s*)lang=(\w+)/.exec(cookie ?? "");
  return match && isLang(match[1]) ? match[1] : "en";
}
/** Locale for dates: Arabic words, Latin digits (VINs and numbers stay readable). */
export function dateLocale(): string {
  return current === "ar" ? "ar-u-nu-latn" : "en-GB";
}

